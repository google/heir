"""Generate test data for the end-to-end ckks.relinearize runner test.

Writes a C++ header containing a secret key, a 3-component ciphertext
(c0, c1, c2), a relinearization key, and the expected phase
c0 + c1*s + c2*s^2. A correct relinearization (d0, d1) must satisfy
d0 + d1*s == expected phase up to a noise bound.

The relinearization key is in coefficient form and follows the hybrid key
switching in lib/Dialect/LWE/Transforms/DecomposeLWEOps.cpp.

Array layouts (row-major, limbs innermost) match the lowered MLIR types:
  ct:       [3][N][len(Q)]
  ksk:      [num_digits][2][N][len(Q) + len(P)]
  expected: [N][len(Q)]

Usage: python3 generate_relinearize_test_data.py <output.h>
"""

import math
import random
import sys

# same parameters as
# tests/Dialect/LWE/Conversions/lwe_to_polynomial/lower_relinearize_to_polynomial.mlir
N = 1024
Q = [1095233372161, 1032955396097]
P = [998595133441]
ERROR_BOUND = 3
SEED = 3022


def negacyclic_mul(a, b, modulus):
  """Multiply a and b in Z_modulus[x] / (x^N + 1)."""
  out = [0] * N
  for i, ai in enumerate(a):
    if ai == 0:
      continue
    for j, bj in enumerate(b):
      k = i + j
      if k < N:
        out[k] += ai * bj
      else:
        out[k - N] -= ai * bj
  return [x % modulus for x in out]


def add(a, b, modulus):
  return [(x + y) % modulus for x, y in zip(a, b)]


def to_limbs(poly, moduli):
  """Flatten a polynomial to [N][len(moduli)] RNS limbs."""
  return [c % q for c in poly for q in moduli]


def main():
  rng = random.Random(SEED)
  q_prod = math.prod(Q)
  p_prod = math.prod(P)
  qp = q_prod * p_prod

  s = [rng.choice([-1, 0, 1]) for _ in range(N)]
  s_sq = negacyclic_mul(s, s, qp)

  # Uniform c0, c1, c2: the test checks that relinearization preserves the
  # phase, so the ciphertext need not encrypt anything in particular.
  ct = [[rng.randrange(q_prod) for _ in range(N)] for _ in range(3)]
  expected = add(
      add(ct[0], negacyclic_mul(ct[1], s, q_prod), q_prod),
      negacyclic_mul(ct[2], s_sq, q_prod),
      q_prod,
  )

  digits = [Q[i : i + len(P)] for i in range(0, len(Q), len(P))]
  ksk = []
  for digit in digits:
    q_i = math.prod(digit)
    q_hat = q_prod // q_i
    g_i = q_hat * pow(q_hat, -1, q_i)
    a = [rng.randrange(qp) for _ in range(N)]
    e = [rng.randint(-ERROR_BOUND, ERROR_BOUND) for _ in range(N)]
    neg_as = [-x for x in negacyclic_mul(a, s, qp)]
    gadget = [p_prod * g_i * x for x in s_sq]
    b = add(add(neg_as, e, qp), gadget, qp)
    ksk.append((b, a))

  # Nise bound for the relinearized phase: each digit contributeso at most
  # N * (Q_i / 2) * ERROR_BOUND / P, and mod-down rounding adds at most
  # (N + 1) / 2. Double it for slack; it is still far below any limb.
  noise_bound = 2 * (
      sum(N * math.prod(d) // 2 * ERROR_BOUND // p_prod for d in digits)
      + (N + 1) // 2
  )

  qp_basis = Q + P

  def array(name, values):
    body = ", ".join(str(v) for v in values)
    return f"inline constexpr int64_t {name}[] = {{{body}}};\n"

  with open(sys.argv[1], "w") as f:
    f.write("// Generated by generate_relinearize_test_data.py. Do not edit.\n")
    f.write("#include <cstdint>\n\n")
    f.write(f"inline constexpr int64_t kN = {N};\n")
    f.write(f"inline constexpr int64_t kNumQ = {len(Q)};\n")
    f.write(f"inline constexpr int64_t kNumDigits = {len(digits)};\n")
    f.write(f"inline constexpr int64_t kNoiseBound = {noise_bound};\n")
    f.write(array("kQ", Q))
    f.write(array("kSecretKey", s))
    f.write(array("kCiphertext", [x for c in ct for x in to_limbs(c, Q)]))
    relin_key = []
    for b, a in ksk:
      relin_key += to_limbs(b, qp_basis) + to_limbs(a, qp_basis)
    f.write(array("kRelinKey", relin_key))
    f.write(array("kExpectedPhase", to_limbs(expected, Q)))


if __name__ == "__main__":
  main()
