"""HEIR: an MLIR-based compiler for fully homomorphic encryption.

This package contains Python bindings for HEIR's MLIR dialects, passes, and
code emitters, plus a thin layer of convenience functions on top of them.

Example:

  import heir

  with heir.context():
    module = heir.parse(open("input.mlir").read())
    heir.run(
        module,
        heir.Pass("annotate-module", backend="openfhe", scheme="bgv"),
        "mlir-to-bgv",
        "scheme-to-openfhe",
    )
    header = heir.translate(module, "emit-openfhe-pke-header")
    source = heir.translate(module, "emit-openfhe-pke")

The MLIR Python API lives in the usual places under this package, e.g.
`heir.ir`, `heir.passmanager`, and `heir.dialects.<dialect>` for both upstream
MLIR dialects (`arith`, `func`, `tensor`, ...) and HEIR dialects (`secret`,
`bgv`, `ckks`, `lwe`, `openfhe`, ...).
"""

import sys as _sys

# Keep in sync with `requires-python` in pyproject.toml. The native extensions
# use the stable ABI of this Python version, and can't be loaded by older ones.
if _sys.version_info < (3, 12):
  raise ImportError(
      "heir requires Python 3.12 or newer, but this is Python"
      f" {_sys.version.split()[0]}"
  )


def _find_generated_sources() -> None:
  """Finds the generated parts of the package for editable installs.

  Most of this package (the upstream MLIR python sources, the generated dialect
  bindings, the native libraries, and the heir-opt and heir-translate
  launchers) is generated by bazel. A wheel (or the bazel-built package)
  contains them, but the source tree (python/heir), which an editable install
  (`pip install -e .`) imports, does not. In that case, add the copy of the
  bazel-built package that `pip install -e .` makes in build/editable/heir to
  this package's search path, so that the generated modules are found there,
  while the hand-written ones are still imported from the source tree.
  """
  import pathlib  # pylint: disable=g-import-not-at-top

  here = pathlib.Path(__file__).resolve().parent
  if (here / "ir.py").exists():
    return
  repo = here.parents[1]
  generated = repo / "build" / "editable" / "heir"
  if not (generated / "ir.py").exists():
    raise ImportError(
        f"heir is imported from its source tree ({here}), but the generated"
        f" parts of the package are missing from {generated}. Build them by"
        f" running `pip install -e .` in {repo}."
    )
  __path__.append(str(generated))


_find_generated_sources()

